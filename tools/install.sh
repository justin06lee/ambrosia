#!/usr/bin/env sh
# Installs the generated themes for the current user (XDG directories).
# Files ambrosia didn't write are kept as <name>.before-ambrosia, never lost.
set -eu

dist="$(cd "$(dirname "$0")/.." && pwd)/dist"

if [ "$(uname -s)" != "Linux" ]; then
  echo "ambrosia: themes install on Linux only; the generated files are in dist/"
  exit 0
fi

config="${XDG_CONFIG_HOME:-$HOME/.config}"
data="${XDG_DATA_HOME:-$HOME/.local/share}"

place() {
  mkdir -p "$(dirname "$2")"
  if [ -f "$2" ] && ! grep -q "Generated by ambrosia" "$2"; then
    mv "$2" "$2.before-ambrosia"
    echo "  kept your previous file as $2.before-ambrosia"
  fi
  cp "$1" "$2"
  echo "  $2"
}

# GTK3 can't follow the system scheme by itself, so install the active one.
mode=light
if command -v gsettings >/dev/null 2>&1 &&
  gsettings get org.gnome.desktop.interface color-scheme 2>/dev/null | grep -q dark; then
  mode=dark
fi

echo "ambrosia: installing themes ($mode)"
place "$dist/gtk-4.0/gtk.css" "$config/gtk-4.0/gtk.css"
place "$dist/gtk-3.0/gtk-$mode.css" "$config/gtk-3.0/gtk.css"
place "$dist/kde/AmbrosiaLight.colors" "$data/color-schemes/AmbrosiaLight.colors"
place "$dist/kde/AmbrosiaDark.colors" "$data/color-schemes/AmbrosiaDark.colors"
place "$dist/fontconfig/50-ambrosia.conf" "$config/fontconfig/conf.d/50-ambrosia.conf"
place "$dist/environment.d/50-ambrosia-fonts.conf" "$config/environment.d/50-ambrosia-fonts.conf"

rm -rf "$data/ambrosia/qml/Ambrosia"
mkdir -p "$data/ambrosia/qml"
cp -R "$dist/qml/Ambrosia" "$data/ambrosia/qml/"
echo "  $data/ambrosia/qml/Ambrosia"

if command -v plasma-apply-colorscheme >/dev/null 2>&1; then
  scheme=AmbrosiaLight
  [ "$mode" = dark ] && scheme=AmbrosiaDark
  plasma-apply-colorscheme "$scheme" >/dev/null && echo "  applied KDE color scheme $scheme"
fi
command -v fc-cache >/dev/null 2>&1 && fc-cache -f >/dev/null
echo "ambrosia: done. Font rendering changes apply from your next login."
