import { size, windowGlyphs, type ShadowLayer } from "../../../design/tokens";
import { toCss, withAlpha, type RGBA } from "../color";

export const HEADER = "Generated by ambrosia tools/gen from design/tokens.ts. Do not edit.";

export const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

/** Token keys like "0.5" become identifier-safe "0_5". */
export const slug = (s: string) => s.replace(".", "_");

export const fontStack = (families: readonly string[], fallback: string) =>
  [...families.map((f) => `"${f}"`), fallback].join(", ");

export const cssShadow = (layers: ShadowLayer[], ink: RGBA) =>
  layers.map(([x, y, blur, spread, a]) => `${x}px ${y}px ${blur}px ${spread}px ${toCss(withAlpha(ink, a))}`).join(", ");

/** Logical px → typographic points at 96 dpi, the unit GTK and KDE take. */
export const pt = (px: number) => +(px * 0.75).toFixed(2);

// The traffic lights' hover glyphs ------------------------------------------------

export type Point = [number, number];
export type Glyph = "close" | "minimize" | "zoom" | "plus";

/** The hover glyphs as filled polygons on the light's 14-unit box, clockwise,
 *  from `windowGlyphs`. Every toolkit draws these same shapes. */
export function windowGlyphPolygons(): Record<Glyph, Point[][]> {
  const g = windowGlyphs;
  const round = (polys: Point[][]) => polys.map((p) => p.map(([x, y]): Point => [+x.toFixed(3), +y.toFixed(3)]));

  // The ×'s outline: the union of the two bars, |x − y| ≤ d and |x + y − 2m| ≤ d.
  const [lo, hi] = g.close.box;
  const m = (lo + hi) / 2;
  const d = g.close.stroke / Math.SQRT2;
  const close: Point[] = [
    [lo, lo], [lo + d, lo], [m, m - d], [hi - d, lo], [hi, lo], [hi, lo + d], [m + d, m], [hi, hi - d],
    [hi, hi], [hi - d, hi], [m, m + d], [lo + d, hi], [lo, hi], [lo, hi - d], [m - d, m], [lo, lo + d],
  ];

  // The capsule, across the light's middle: a half circle round each end, eight segments each.
  const mid = size.windowControls.diameter / 2;
  const arc = (cx: number, cy: number, r: number, from: number): Point[] =>
    Array.from({ length: 9 }, (_, i) => {
      const angle = from + (Math.PI * i) / 8;
      return [cx + r * Math.cos(angle), cy + r * Math.sin(angle)];
    });
  const [a, b] = g.minimize.ends;
  const r = g.minimize.radius;
  const minimize = [...arc(b, mid, r, -Math.PI / 2), ...arc(a, mid, r, Math.PI / 2)];

  // The plus: that capsule and its upright twin as one outline, arm by arm from the right.
  const [pa, pb] = g.plus.ends;
  const pr = g.plus.radius;
  const plus: Point[] = [
    ...arc(pb, mid, pr, -Math.PI / 2), [mid + pr, mid + pr],
    ...arc(mid, pb, pr, 0), [mid - pr, mid + pr],
    ...arc(pa, mid, pr, Math.PI / 2), [mid - pr, mid - pr],
    ...arc(mid, pa, pr, Math.PI), [mid + pr, mid - pr],
  ];

  // Two right triangles in opposite corners; their hypotenuses sit gap/2 either side of the diagonal.
  const [zlo, zhi] = g.zoom.box;
  const leg = zhi - zlo - g.zoom.gap / Math.SQRT2;
  const zoom: Point[][] = [
    [[zlo, zlo], [zlo + leg, zlo], [zlo, zlo + leg]],
    [[zhi, zhi], [zhi - leg, zhi], [zhi, zhi - leg]],
  ];

  return { close: round([close]), minimize: round([minimize]), zoom: round(zoom), plus: round([plus]) };
}

/** Polygons as SVG path data. */
export const svgPath = (polys: Point[][]) =>
  polys.map((p) => `M${p.map(([x, y]) => `${x} ${y}`).join("L")}Z`).join("");
