import type { ShadowLayer } from "../../../design/tokens";
import { toCss, withAlpha, type RGBA } from "../color";

export const HEADER = "Generated by ambrosia tools/gen from design/tokens.ts. Do not edit.";

export const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

/** Token keys like "0.5" become identifier-safe "0_5". */
export const slug = (s: string) => s.replace(".", "_");

export const fontStack = (families: readonly string[], fallback: string) =>
  [...families.map((f) => `"${f}"`), fallback].join(", ");

export const cssShadow = (layers: ShadowLayer[], ink: RGBA) =>
  layers.map(([x, y, blur, spread, a]) => `${x}px ${y}px ${blur}px ${spread}px ${toCss(withAlpha(ink, a))}`).join(", ");

/** Logical px → typographic points at 96 dpi, the unit GTK and KDE take. */
export const pt = (px: number) => +(px * 0.75).toFixed(2);
